#!/usr/bin/env python3
"""
Extract and organize MSAs generated by Boltz, Chai, and Protenix into a structured format.
This script should be run after MSA generation is complete.

Author: Oliver Sun
Date: 2025-07-29
"""

import os
import argparse
import glob
import shutil
import pickle
from pathlib import Path
from typing import Dict, List, Any, Optional


def parse_fasta(fasta_path: str) -> Dict[str, Dict]:
    """
    Parse FASTA file into a dictionary with detailed protein information.
    
    Args:
        fasta_path: Path to FASTA file
        
    Returns:
        Dictionary mapping protein names to dictionaries containing:
        - sequence: The protein sequence
        - full_header: The complete FASTA header
        - index: The position in the FASTA file (0-based)
    """
    proteins = {}
    current_name = None
    current_header = None
    current_seq = []
    index = 0
    
    with open(fasta_path, 'r') as f:
        lines = f.readlines()
    for line in lines:
        line = line.strip()
        if line.startswith('>'):
            if current_name:
                proteins[current_name] = {
                    'sequence': ''.join(current_seq),
                    'full_header': current_header,
                    'index': index - 1  # Adjust index to be 0-based
                }
            current_header = line
            # Extract name before first | or use the whole header if no | is present
            if '|' in line[1:]:
                current_name = line[1:].split('|')[0]
            else:
                current_name = line[1:]
            current_seq = []
            index += 1
        else:
            current_seq.append(line)
    
    if current_name:
        proteins[current_name] = {
            'sequence': ''.join(current_seq),
            'full_header': current_header,
            'index': index - 1  # Adjust index to be 0-based
        }
    
    return proteins


def extract_boltz_msa(output_dir: str, combo_name: str, protein_name: str, final_dir: str) -> bool:
    """
    Extract Boltz MSA to the final directory using Python file operations.
    
    Args:
        output_dir: Base output directory
        combo_name: Combination name
        protein_name: Name of the protein
        final_dir: Final directory to store MSAs
        
    Returns:
        bool: True if extraction was successful, False otherwise
    """
    os.makedirs(final_dir, exist_ok=True)
    
    # Find the Boltz MSA CSV file
    search_pattern = os.path.join(output_dir, "boltz", f"boltz_results_{combo_name}", "msa", "*.csv")
    csv_files = glob.glob(search_pattern)
    
    if not csv_files:
        print(f"Warning: No Boltz MSA found for {protein_name}")
        return False
    
    # Copy the first CSV file found
    source_file = csv_files[0]
    target_file = os.path.join(final_dir, f"{protein_name}.csv")
    
    try:
        shutil.copy2(source_file, target_file)
        print(f"Extracted Boltz MSA: {protein_name}.csv")
        return True
    except Exception as e:
        print(f"Error extracting Boltz MSA for {protein_name}: {e}")
        return False


def extract_chai_msa(output_dir: str, combo_name: str, protein_name: str, final_dir: str) -> bool:
    """
    Extract Chai MSA to the final directory using Python file operations.
    
    Args:
        output_dir: Base output directory
        combo_name: Combination name
        protein_name: Name of the protein
        final_dir: Final directory to store MSAs
        
    Returns:
        bool: True if extraction was successful, False otherwise
    """
    protein_dir = os.path.join(final_dir, protein_name)
    os.makedirs(protein_dir, exist_ok=True)
    
    # Find Chai MSA files
    search_pattern = os.path.join(output_dir, "chai", protein_name, "msas", "*.aligned.pqt")
    pqt_files = glob.glob(search_pattern)
    
    if not pqt_files:
        print(f"Warning: No Chai MSA found for {protein_name}")
        return False
    
    # Copy all aligned.pqt files
    success = True
    for pqt_file in pqt_files:
        try:
            target_file = os.path.join(protein_dir, os.path.basename(pqt_file))
            shutil.copy2(pqt_file, target_file)
        except Exception as e:
            print(f"Error copying Chai MSA file {pqt_file}: {e}")
            success = False
    
    if success:
        print(f"Extracted Chai MSA: {protein_name}/ ({len(pqt_files)} files)")
    
    return success


def extract_protenix_msa(output_dir: str, final_dir: str, seq_to_name_map: dict) -> bool:
    """
    Extract Protenix MSA to the final directory using Python file operations.
    
    Args:
        output_dir: Base output directory (should be the protenix output directory)
        final_dir: Final directory to store MSAs
        seq_to_name_map: Mapping from sequences to protein names
        
    Returns:
        bool: True if extraction was successful, False otherwise
    """
    if not os.path.exists(output_dir):
        print(f"Warning: Protenix output directory {output_dir} does not exist")
        return False
    
    # Create a mapping from sequence to index by reading pairing.a3m files
    seq_to_index_map = {}
    
    # Find all pairing.a3m files
    for root, dirs, files in os.walk(output_dir):
        if "pairing.a3m" in files:
            # Extract the index from the path (directory name right before pairing.a3m)
            index = os.path.basename(root)
            
            # Read the second line of the file to get the sequence
            pairing_file = os.path.join(root, "pairing.a3m")
            try:
                with open(pairing_file, 'r') as f:
                    # Skip the first line
                    f.readline()
                    # Read the second line (the sequence)
                    sequence = f.readline().strip()
                    
                # Add to our mapping
                seq_to_index_map[sequence] = index
            except Exception as e:
                print(f"Error reading pairing file {pairing_file}: {e}")
                continue
    
    # Create protein_index_map using seq_to_name_map and seq_to_index_map
    protein_index_map = {}
    for seq, name in seq_to_name_map.items():
        if seq in seq_to_index_map:
            protein_index_map[name] = seq_to_index_map[seq]
    
    if not protein_index_map:
        print("Warning: No Protenix MSA mappings found")
        return False
    
    # Extract MSAs for each protein
    success = True
    for protein_name, protein_index in protein_index_map.items():
        protein_dir = os.path.join(final_dir, protein_name)
        os.makedirs(protein_dir, exist_ok=True)
        
        # Source directory for this protein's MSA
        source_dir = os.path.join(output_dir, protein_index)
        
        if not os.path.exists(source_dir):
            print(f"Warning: Protenix MSA directory {source_dir} not found for {protein_name}")
            success = False
            continue
        
        # Copy all files from the source directory
        try:
            for item in os.listdir(source_dir):
                source_item = os.path.join(source_dir, item)
                target_item = os.path.join(protein_dir, item)
                
                if os.path.isfile(source_item):
                    shutil.copy2(source_item, target_item)
                elif os.path.isdir(source_item):
                    shutil.copytree(source_item, target_item, dirs_exist_ok=True)
            
            print(f"Extracted Protenix MSA: {protein_name}/")
        except Exception as e:
            print(f"Error extracting Protenix MSA for {protein_name}: {e}")
            success = False
    
    return success


def main():
    """Main function for MSA extraction."""
    parser = argparse.ArgumentParser(description='Extract and organize MSAs generated by multiple methods.')
    parser.add_argument('fasta', help='Path to FASTA file with protein sequences')
    parser.add_argument('--output-dir', default='tmp/msa_generation',
                       help='Base output directory containing intermediate results')
    parser.add_argument('--final-dir', default='tmp/msas',
                       help='Final directory to store organized MSA files')
    parser.add_argument('--methods', nargs='+', choices=['boltz', 'chai', 'protenix'], 
                       default=['boltz', 'chai', 'protenix'],
                       help='Methods to extract MSAs for (default: all)')
    
    args = parser.parse_args()
    
    # Convert all paths to absolute paths
    fasta_path = Path(args.fasta).resolve()
    output_dir = Path(args.output_dir).resolve()
    final_dir = Path(args.final_dir).resolve()
    
    # Create final directory
    os.makedirs(final_dir, exist_ok=True)
    
    # Parse FASTA file
    proteins = parse_fasta(str(fasta_path))
    print(f"Found {len(proteins)} proteins in FASTA file")
    
    # Create sequence to name mapping for Protenix
    seq_to_name_map = {info['sequence']: name for name, info in proteins.items()}
    
    # Track extraction results
    extraction_results = {}
    
    # Extract MSAs for each method
    for method in args.methods:
        print(f"\n=== Extracting {method.upper()} MSAs ===")
        method_final_dir = final_dir / method
        os.makedirs(method_final_dir, exist_ok=True)
        
        if method == 'boltz':
            extraction_results[method] = {}
            for protein_name, protein_info in proteins.items():
                combo_name = f"{protein_name}_msa_gen"
                success = extract_boltz_msa(
                    output_dir=str(output_dir / "outputs"),
                    combo_name=combo_name,
                    protein_name=protein_name,
                    final_dir=str(method_final_dir)
                )
                extraction_results[method][protein_name] = success
                
        elif method == 'chai':
            extraction_results[method] = {}
            for protein_name, protein_info in proteins.items():
                combo_name = f"{protein_name}_msa_gen"
                success = extract_chai_msa(
                    output_dir=str(output_dir / "outputs"),
                    combo_name=combo_name,
                    protein_name=protein_name,
                    final_dir=str(method_final_dir)
                )
                extraction_results[method][protein_name] = success
                
        elif method == 'protenix':
            success = extract_protenix_msa(
                output_dir=str(output_dir / "outputs" / "protenix"),
                final_dir=str(method_final_dir),
                seq_to_name_map=seq_to_name_map
            )
            extraction_results[method] = {'overall': success}
    
    # Generate protein MSA metadata
    print(f"\n=== Generating MSA metadata ===")
    protein_msa_file = final_dir / "protein_msa_metadata.pkl"
    protein_msa_map = {}
    
    for name, info in proteins.items():
        protein_msa_map[name] = {
            'sequence': info['sequence']
        }
        if 'boltz' in args.methods:
            protein_msa_map[name]['boltz_msa'] = f"boltz/{name}.csv"
        if 'chai' in args.methods:
            protein_msa_map[name]['chai_msa'] = f"chai/{name}/"
        if 'protenix' in args.methods:
            protein_msa_map[name]['protenix_msa'] = f"protenix/{name}/"
    
    with open(protein_msa_file, 'wb') as f:
        pickle.dump(protein_msa_map, f)
    
    print(f"Generated MSA metadata: {protein_msa_file}")
    
    # Print summary
    print(f"\n=== Extraction Summary ===")
    for method, results in extraction_results.items():
        if method == 'protenix':
            status = "✓" if results.get('overall', False) else "✗"
            print(f"{method.upper()}: {status}")
        else:
            successful = sum(1 for success in results.values() if success)
            total = len(results)
            print(f"{method.upper()}: {successful}/{total} proteins extracted successfully")
    
    print(f"\nMSA extraction completed! Results stored in: {final_dir}")


if __name__ == "__main__":
    main()
