#!/usr/bin/env python3
"""
Step 3: Kinase Cofolding Analysis

This script generates a single bash script containing all individual scripts to process
folders under examples/predictions using the main_pipeline.py script.
The generated script is saved in the examples/scripts folder.
"""

import os
import sys
import argparse
from pathlib import Path
from datetime import datetime
from cofolding_inference.envs import FOLDER, KINCONFBENCH_ENV, KINCONFBENCH_PREFIX


def _get_conda_run_cmd() -> str:
    """Get conda run command for kinase pipeline env (prefix or named)."""
    if KINCONFBENCH_ENV:
        return f"conda run -n {KINCONFBENCH_ENV}"
    return f"conda run --prefix {KINCONFBENCH_PREFIX}"


def generate_individual_script_content(dir_path: Path, verbose: bool = False, comprehensive: bool = False) -> str:
    """
    Generate bash script content to process a single directory of cofolding models.

    Args:
        dir_path: Path to the directory containing CIF files
        verbose: Enable verbose output
        comprehensive: Generate comprehensive CSV output

    Returns:
        String containing the script content
    """
    dir_name = dir_path.name
    output_file = dir_path / f"{dir_name}_analysis.csv"
    analysis_script = FOLDER.parent / "kinase_benchmark" / "kinase_pipeline" / "main_pipeline.py"
    # Create script content
    script_content = f"""#
# Kinase analysis for {dir_name}
#

echo "Processing {dir_name}..."
{_get_conda_run_cmd()} python {analysis_script} \\
    -c \\
    -ff "{dir_path}" \\
    -o "{output_file}" \\
"""

    # Add optional flags
    if verbose:
        script_content += "    -v \\\n"
    if not comprehensive:
        script_content += "    --minimal \\\n"

    # Remove trailing backslash and add newline
    script_content = script_content.rstrip("\\\n") + "\n\n"

    return script_content


def generate_combined_script(
    subdirs: list,
    scripts_dir: Path,
    verbose: bool = False,
    comprehensive: bool = False,
) -> str:
    """
    Generate a single bash script that contains all individual scripts.

    Args:
        subdirs: List of paths to subdirectories to process
        scripts_dir: Directory to save the generated script
        verbose: Enable verbose output in generated script
        comprehensive: Generate comprehensive CSV output

    Returns:
        Path to the generated script
    """
    script_name = "run_all_kinase_analyses.sh"
    script_path = scripts_dir / script_name

    # Create script header
    script_content = f"""#!/bin/bash
# Combined script for all kinase analyses
# Generated by step_3_kinase_cofolding_analysis.py on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

echo "Starting kinase analysis for all prediction folders..."

# Track successful analyses
SUCCESSFUL_ANALYSES=0
TOTAL_ANALYSES={len(subdirs)}

"""

    # Add individual script content for each subdirectory
    for i, subdir in enumerate(sorted(subdirs), 1):
        dir_name = subdir.name
        script_content += f"""#----------------------------------------------------------------------
# [{i}/{len(subdirs)}] Analysis for {dir_name}
#----------------------------------------------------------------------
echo "[{i}/{len(subdirs)}] Processing {dir_name}..."

{generate_individual_script_content(subdir, verbose, comprehensive)}
if [ $? -eq 0 ]; then
    SUCCESSFUL_ANALYSES=$((SUCCESSFUL_ANALYSES+1))
    echo "✓ Analysis for {dir_name} completed successfully."
else
    echo "✗ Warning: Analysis failed for {dir_name}"
fi

"""

    # Add summary at the end
    script_content += f"""#----------------------------------------------------------------------
# Summary
#----------------------------------------------------------------------
echo "All analyses complete. $SUCCESSFUL_ANALYSES/$TOTAL_ANALYSES successful."
"""

    # Write script to file
    with open(script_path, "w") as f:
        f.write(script_content)

    # Make script executable
    os.chmod(script_path, 0o755)

    return script_path


def main():
    """Main function for command line usage"""
    parser = argparse.ArgumentParser(
        description="Generate a single script to process all folders under examples/predictions"
    )
    parser.add_argument(
        "-d",
        "--outputs-dir",
        default="examples",
        help="Directory containing cofolding prediction subdirectories",
    )
    parser.add_argument(
        "-f",
        "--filter",
        default=None,
        help="Filter directories by name (e.g., 'afatinib' for only afatinib structures)",
    )
    parser.add_argument(
        "-v", "--verbose", action="store_true", help="Enable verbose output in generated script"
    )
    parser.add_argument(
        "-r",
        "--reduced",
        action="store_true",
        help="Generate reduced CSV output",
    )

    args = parser.parse_args()

    # Create scripts directory if it doesn't exist
    scripts_dir = Path(args.outputs_dir) / "scripts"
    scripts_dir.mkdir(parents=True)

    # Find all subdirectories in the output directory
    predictions_dir = Path(args.outputs_dir) / "predictions"
    if not predictions_dir.exists():
        print(f"Error: Predictions directory {predictions_dir} does not exist")
        sys.exit(1)

    # Get all subdirectories
    subdirs = [d for d in predictions_dir.iterdir() if d.is_dir()]

    # Apply filter if provided
    if args.filter:
        subdirs = [d for d in subdirs if args.filter in d.name]

    if not subdirs:
        print(f"No subdirectories found in {predictions_dir}")
        sys.exit(1)

    print(f"Found {len(subdirs)} directories to process")

    # Generate combined script
    combined_script = generate_combined_script(subdirs, scripts_dir, args.verbose, not args.reduced)

    print(f"\nGenerated combined script: {combined_script}")
    print("\nScript generated successfully!")
    print(f"To run all analyses: bash {combined_script}")


if __name__ == "__main__":
    main()
